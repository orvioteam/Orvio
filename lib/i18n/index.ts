const localeTags: Record<AppLanguage, string> = {
  de: "de-CH",
  en: "en-US",
  fr: "fr-FR",
  it: "it-IT",
};

export function translate(language: AppLanguage, message: string): string {
  return language === "de" ? message : messages[language][message] ?? productMessages[language][message] ?? message;
}

export function translateError(language: AppLanguage, error: unknown, fallback: string): string {
  const message = error instanceof Error ? error.message : "";
  const safeMessage = {
    "Employee not found or invitation is not permitted": "Diese Einladung ist nicht mehr gültig.",
    "Invalid invitation request": "Diese Einladung ist nicht mehr gültig.",
  }[message] ?? message;
  if (safeMessage && (safeMessage in messages.en || safeMessage in productMessages.en)) {
    const translated = translate(language, safeMessage);
    return translated;
  }
  return translate(language, fallback);
}

export function formatLocalizedDate(language: AppLanguage, date: Date, options: Intl.DateTimeFormatOptions = { dateStyle: "long" }): string {
  return new Intl.DateTimeFormat(localeTags[language], options).format(date);
}

export function formatLocalizedDateRange(language: AppLanguage, start: Date, end: Date): string {
  return new Intl.DateTimeFormat(localeTags[language], { dateStyle: "medium" }).formatRange(start, end);
}
